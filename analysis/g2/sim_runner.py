def deck_text(name, params, sources, tstop, tmax, meas, extra=()):
    p = dict(params)
    lines = [f"* G2 case {name}", "* generated by analysis/g2/sim_runner.py", ""]
    lines += [f".param {k}={val:.9g}" for k, val in p.items()]
    lines += [f".param TSTOP={tstop:.9g}", ""]
    lines += sources
    lines += [f".include {os.path.relpath(NETLIST, SIMROOT / 'x').replace(os.sep, '/')}", ""]
    lines += ["BVDS vds 0 V = V(vraw)-V(vsafe)", "BO1IN o1in 0 V = V(o1)-V(vsafe)", "BS2IN s2ein 0 V = V(s2e)-V(vsafe)",
              "BPD pdiss 0 V = V(vraw,vsafe)*i(VMISO)"]
    lines += list(extra)
    # steady-state starts (.ic present): ngspice computes a consistent OP with the .ic node values (no uic);
    # startup cases (no .ic) start from zero with uic. (uic + .ic diverged numerically in 13 runs, attempt logs kept)
    uic = "" if extra else " uic"
    lines += [f".tran {tmax:.3g} {tstop:.9g} 0 {tmax:.3g}{uic}", ".options method=gear reltol=1e-4 abstol=1e-9 vntol=1e-6 itl4=200"]
    for mname, expr in meas:
        lines.append(f".meas tran {mname} {expr.replace('{TSTOP}', f'{tstop:.9g}')}")
    lines.append(".end")
    return "\n".join(lines) + "\n"


def src(vbat_pwl, io1="0", is2="0.22", fault="0", o1ext="0"):
    return [f"VBAT vbat 0 PWL({vbat_pwl})", f"VIO1 io1_set 0 {io1}", f"VIS2 is2_set 0 {is2}",
            f"VFLT fault1 0 {fault}", f"VO1X o1_ext 0 {o1ext}"]


def steady(params, vin, i_total, io1, is2="0.22", fault="0", o1ext="0", vbat=None):
    """Start from regulation: .ic on state nodes, inductor IC via IL0, battery as DC (or given PWL)."""
    p = dict(params)
    p["IL0"] = i_total / 2
    vset = p["VREF_FB"] * VSCALE
    vc0 = p["RI"] * i_total / 2 + p["VCOFS"]
    ic = [f".ic V(vin)={vin} V(anode)={vin} V(n_cin)=0 V(vraw)={vset} V(ncout)=0 V(vsafe)={vset} "
          f"V(o1)={vset} V(s2e)={vset} V(ss)={p['VREF_FB']} V(ens)=1 V(q)=0 V(ctl)=1 V(comp)={vc0} V(cmid)={vc0} "
          f"V(en_ef)={vset * D.REN_EF2 / (D.REN_EF1 + D.REN_EF2)} V(efs)=1 V(il1)={i_total / 2} V(il2)={i_total / 2} V(oct)=0"]
    srcs = src(vbat or f"0 {vin} 1 {vin}", io1=io1, is2=is2, fault=fault, o1ext=o1ext)
    return p, srcs, ic


def step_on(vin, t0=50e-6):
    return f"0 0 {t0:.6g} 0 {t0 + 1e-6:.6g} {vin}"


def fault_at(tf=TF):
    return f"PWL(0 0 {tf:.6g} 0 {tf + 10e-9:.6g} 1)"


