# --------------------------------------------------------------------------- runner
def _sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def parse_meas(log_text, names):
    out = {}
    for n in names:
        m = re.search(rf"^{n}\s*=\s*([-+0-9.eE]+)", log_text, re.M | re.I)
        if m:
            out[n] = float(m.group(1))
    return out


def run_case(name, fam, params, sources, tstop, tmax, meas, crit, extra=()):
    d = SIMROOT / fam.lower()
    d.mkdir(parents=True, exist_ok=True)
    deck = d / f"{name}.cir"
    log = d / f"{name}.log"
    text = deck_text(name, params, sources, tstop, tmax, meas, extra)
    if deck.exists() and deck.read_text(encoding="utf-8") != text and log.exists():
        k = 1
        while (d / f"{name}-attempt{k}.cir").exists():
            k += 1
        shutil.move(str(deck), str(d / f"{name}-attempt{k}.cir"))
        shutil.move(str(log), str(d / f"{name}-attempt{k}.log"))
    deck.write_text(text, encoding="utf-8", newline="\n")
    try:
        p = subprocess.run([str(NGSPICE), "-b", "-o", log.name, deck.name], cwd=d, capture_output=True, text=True, timeout=300)
        code = p.returncode
    except subprocess.TimeoutExpired:
        code = -9
    lt = log.read_text(errors="replace") if log.exists() else ""
    names = [m[0] for m in meas]
    vals = parse_meas(lt, names)
    completed = code == 0 and len(vals) == len(names)
    verdict = {}
    for k, (op, lim) in crit.items():
        if k not in vals:
            verdict[k] = None
            continue
        x = vals[k]
        verdict[k] = {"<": x < lim, "<=": x <= lim, ">": x > lim, ">=": x >= lim}[op]
    passed = completed and all(verdict.values())
    inputs_sha = hashlib.sha256((NETLIST.read_text(encoding="utf-8") + text).encode()).hexdigest()
    return {"family": fam, "deck": str(deck.relative_to(ROOT)).replace("\\", "/"),
            "log": str(log.relative_to(ROOT)).replace("\\", "/"), "exit": code, "completed": completed,
            "missing": [n for n in names if n not in vals], "measures": vals,
            "criteria": {k: {"op": op, "limit": lim, "pass": verdict[k]} for k, (op, lim) in crit.items()},
            "pass": passed, "deck_sha256": _sha(deck), "log_sha256": _sha(log) if log.exists() else None,
            "inputs_sha256": inputs_sha}


def main(argv):
    write_param_inc()
    fams = set(a.upper() for a in argv) or {"F1", "F2", "F3", "F4", "F5"}
    cases = family_cases()
    prev = json.loads(OUTJ.read_text(encoding="utf-8")) if OUTJ.exists() else {"runs": {}}
    # keep only cases defined now (renamed/obsolete runs are dropped from the summary; their files go to archive/)
    runs = {n: r for n, r in prev.get("runs", {}).items() if n in cases}
    for name, (fam, p, s, tstop, tmax, meas, crit, extra) in cases.items():
        if fam not in fams:
            continue
