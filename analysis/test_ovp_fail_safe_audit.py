def test_saved_negative_fixture_exposes_missing_clamp_and_screened_clamp_path():
    root = Path(__file__).resolve().parents[1]
    result = json.loads((root / "reports/g1/fail-safe-audit-results.json").read_text(encoding="utf-8"))
    fixture = result["negative_fixture"]
    assert fixture["completed"] is True
    m = fixture["measures"]
    assert m["inp_a_after_loss"] > 2.2
    assert m["g1a_after_loss"] > 9.0 and m["g2a_after_loss"] > 9.0
    assert m["inp_b_after_loss"] < 0.01
    assert m["g1b_after_loss"] < 0.01 and m["g2b_after_loss"] < 0.01
    assert "not physically verified" in " ".join(fixture["limitations"])


def test_machine_status_register_preserves_physical_open_and_behavioral_fail():
    results = build_results(run_spice=False)
    rows = results["status_register"]
    status = {row["item"]: row["status"] for row in rows}
    assert status["VCC below 1.65V implies latch safe"] == "FAIL"
    assert status["present CLR/ARM/PG/INP/FET network"] == "OPEN"
    assert status["no-clamp stuck-high INP fixture"] == "FAIL"
    assert status["ideal clamp negative fixture"] == "PASS"
    assert status["O1 <=12V and normal bus <=11.1605V physical acceptance"] == "OPEN"
    pins = results["datasheet_pin_contract"]
    assert pins["TPS7A16QDGNRQ1_DGN8"]["PG"] == 3
    assert pins["CSD19536KTTT_D2PAK_each"] == {"G": 1, "D": 2, "S": 3, "tab": "D"}
