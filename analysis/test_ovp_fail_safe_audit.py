def test_below_latch_minimum_supply_is_unspecified_not_safe():
    assert latch_next_q(True, vcc_v=LATCH_MIN_VCC_V - 0.01, clr_n=False,
                        pre_n=True, arm_edge=False,
                        arm_permitted=False) is None


def test_fault_clear_dominates_arm_and_release_does_not_rearm():
    q = next_latch_state(False, vcc_v=5.0, pg_ok=True, raw_safe=True,
                         monitors_healthy=True, arm_edge=True)
    assert q is True
    q = next_latch_state(q, vcc_v=5.0, pg_ok=True, raw_safe=False,
                         monitors_healthy=False, arm_edge=True)
    assert q is False
    q = next_latch_state(q, vcc_v=5.0, pg_ok=True, raw_safe=True,
                         monitors_healthy=True, arm_edge=False)
    assert q is False


def test_preset_clear_simultaneous_low_is_rejected_as_nonstable():
    assert latch_next_q(False, vcc_v=5.0, clr_n=False, pre_n=False,
                        arm_edge=True, arm_permitted=True) is None


def test_unsafe_manual_arm_is_rejected_and_cold_start_requires_clear():
    assert next_latch_state(False, vcc_v=5.0, pg_ok=False, raw_safe=False,
                            monitors_healthy=False, arm_edge=True) is False
    assert latch_next_q(None, vcc_v=5.0, clr_n=True, pre_n=True,
                        arm_edge=False, arm_permitted=False) is None
    assert latch_next_q(None, vcc_v=5.0, clr_n=False, pre_n=True,
                        arm_edge=False, arm_permitted=False) is False


def test_latch_output_loss_does_not_imply_driver_input_or_gate_off():
    # Below 1.65V the DFF output is outside its operating specification.
    # The LTC7001 remains powered in this corner; only a separate low clamp
    # plus gate-source discharge path can make the fail-off requirement true.
    q = latch_next_q(True, vcc_v=1.0, clr_n=False, pre_n=True,
                     arm_edge=False, arm_permitted=False)
    assert q is None
    deck = build_control_loss_deck()
    assert "VDRIVER VDRIVER 0 12" in deck
    assert "SMON INP_B 0 MON_BAD 0 IDEALCLAMP" in deck
    assert all(token in deck for token in ("CG1B", "CG2B", "RGS1B", "RGS2B"))


def test_ldo_thermal_separates_normal_sustained_fault_and_pulse():
    data = thermal_screen(85.0)
    rows = data["sources"]
    assert rows["VRAW_normal_11V_sustained"]["Tj_C_at_assumed_ambient"] == pytest.approx(92.75, abs=0.3)
    assert rows["VRAW_fault_26V_sustained"]["Tj_C_at_assumed_ambient"] == pytest.approx(111.8, abs=0.5)
    assert rows["VRAW_fault_40p709V_sustained_hypothetical"]["Tj_C_at_assumed_ambient"] == pytest.approx(130.45, abs=0.5)
    assert rows["protected_VIN_max_26V_sustained"]["below_conservative_125C_screen"] is True
    assert rows["VRAW_fault_40p709V_sustained_hypothetical"]["below_conservative_125C_screen"] is False
    assert data["125C_is_TI_limit"] is False
    assert data["VRAW_40p709V_fault_pulse"]["Tj_peak_C"] is None


def test_bleeder_and_efuse_reverse_current_are_open_not_physical_passes():
    data = thermal_screen(85.0)
    assert data["bleeder"]["I_mA_at_5p1V_Rmin"] == pytest.approx(10.961, abs=0.002)
    assert data["bleeder"]["P_mW_at_5p1V_Rmin"] == pytest.approx(55.9, abs=0.2)
    efuse = build_results(run_spice=False)["input_loss_efuse"]
    assert efuse["datasheet_reverse_current_block_guarantee_found"] is False
    assert efuse["11V_precharge_input_loss_screen"]["conditional_excess_V"] == pytest.approx(10.7)
    assert efuse["11V_precharge_input_loss_screen"]["status"].startswith("FAIL if")
    # The committed report is generated by the audit runner and tags the old
    # negative charge as an ideal bilateral-switch artifact.
    root = Path(__file__).resolve().parents[1]
    result_path = root / "reports/g1/fail-safe-audit-results.json"
    if result_path.exists():
        result = json.loads(result_path.read_text(encoding="utf-8"))
        assert result["input_loss_efuse"]["datasheet_reverse_current_block_guarantee_found"] is False
        assert "ideal bilateral SW artifact" in result["input_loss_efuse"]["old_Q_EF2_minus_44p547uC"]


