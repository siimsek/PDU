"""T-007 schematic block B2 (buck core) — reproducible edit of PDU.kicad_sch with the lossless S-expression tool.

    python scripts/sch_edit_b2.py      # run on a tree where B1 is applied; revert with git checkout -- PDU.kicad_sch

Edits (spec = design/pdu_v2_spec.yaml, generated by analysis/g2/bom.py):
  * U1/U2 pin 6 BIAS: label VOUT -> GND (G4 B3, LM70880 p.13: unused BIAS to AGND).
  * CBOOTk pin 1 node named CBOOT_Rk (series RBOOT, LM70880 p.4).
  * R_INJ (0 ohm, FRA injection) inserted between /VOUT and RFB1 pin 1 (new net /FB_INJ).
  * R_TRIM (442 ohm) inserted between RFB2 pin 2 (new net /FB_TRIM) and the existing GND wire.
  * Value / Footprint / MPN of every B2 part from the spec (RCOMP 33.2k, CCOMP 10n, CHF 22p, RFB2 9.76k, ...).
"""
from __future__ import annotations

import re
import sys
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kicad_sexpr as ks  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SCH = ROOT / "PDU.kicad_sch"
B2_REFS = ["U1", "U2", "L1", "L2", "RS1", "RS2", "CBOOT1", "CBOOT2", "RBOOT1", "RBOOT2", "RT1", "RT2", "CVCC1", "CVCC2",
           "CVDDA1", "CVDDA2", "RCFG1", "RCFG2", "RSYNC", "RFB1", "R_INJ", "RFB2", "R_TRIM", "RCOMP", "CCOMP", "CHF",
           "RUV1", "RUV2"]
NUMERIC = re.compile(r"^[0-9.]+[pnumkMR]?$")


def uid(tag: str) -> str:
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"PDU/T-007/{tag}"))


def label_text(name: str, pt, tag: str) -> str:
    return (f'(label "{name}"\n\t\t(at {pt[0]:g} {pt[1]:g} 0)\n\t\t(effects\n\t\t\t(font\n\t\t\t\t(size 1.27 1.27)\n'
            f'\t\t\t)\n\t\t\t(justify left bottom)\n\t\t)\n\t\t(uuid "{uid(tag)}")\n\t)')


def clone_resistor(root, sch, template_ref: str, ref: str, at, rot: int) -> ks.SList:
    """Copy a placed Device:R symbol, give it a new reference, position, rotation and uuid."""
    src = ks.symbol_by_ref(root, template_ref)
    txt = ks.dump(src)
    x0, y0 = ks.at_of(src)
    txt = txt.replace(f'(reference "{template_ref}")', f'(reference "{ref}")')
    txt = txt.replace(f'(property "Reference" "{template_ref}"', f'(property "Reference" "{ref}"')
    txt = re.sub(r'\(uuid "[^"]+"\)', f'(uuid "{uid(ref)}")', txt, count=1)
    txt = re.sub(r"\(at ([-0-9.]+) ([-0-9.]+) ([-0-9.]+)\)",
                 lambda m: f"(at {float(m.group(1)) - x0 + at[0]:g} {float(m.group(2)) - y0 + at[1]:g} {rot if m.start() == txt.find('(at ') else m.group(3)})",
                 txt)
    node = ks.insert_after(sch, src, txt)
    for extra in ("Specification", "TCR", "Tolerance", "Manufacturer"):  # template-specific fields
        ks.remove_property(root, ref, extra)
    ks.set_property(root, ref, "Datasheet", "")
    return node


def apply(text: str, spec: dict) -> tuple[str, list]:
    root = ks.parse(text)
    sch = ks.top(root)
    log = []
    for ref in ("U1", "U2"):                                   # BIAS (pin 6) -> GND
        pt = ks.pin_points(sch, root, ref)["6"]
        for kind, name, node in ks.items_at(sch, pt):
            if kind == "label" and name == "VOUT":
                ks.set_label_text(node, "GND")
                log.append(f"{ref}.6 label VOUT -> GND at {pt}")
    for k in (1, 2):                                           # name the series RBOOT/CBOOT node
        pt = ks.pin_points(sch, root, f"CBOOT{k}")["1"]
        if not any(kind == "label" for kind, *_ in ks.items_at(sch, pt)):
            ks.insert_after(sch, next(sch.children("label")), label_text(f"CBOOT_R{k}", pt, f"CBOOT_R{k}"))
            log.append(f"label CBOOT_R{k} at {pt}")
    if ks.symbol_by_ref(root, "R_INJ") is None:                # R_INJ: /VOUT -> R_INJ -> /FB_INJ -> RFB1.1
        p1 = ks.pin_points(sch, root, "RFB1")["1"]
        clone_resistor(root, sch, "RFB1", "R_INJ", (p1[0] + 3.81, p1[1]), 270)  # pin 2 meets RFB1.1, pin 1 = /VOUT (spec)
        rp = ks.pin_points(sch, root, "R_INJ")
        far = next(p for p in rp.values() if abs(p[0] - p1[0]) > 1 or abs(p[1] - p1[1]) > 1)
        for kind, name, node in ks.items_at(sch, p1):
            if kind == "label" and name == "VOUT":
                ks.set_label_text(node, "FB_INJ")
        ks.insert_after(sch, next(sch.children("label")), label_text("VOUT", far, "R_INJ-VOUT"))
        log.append(f"R_INJ placed, pins {rp}; RFB1.1 label VOUT -> FB_INJ, VOUT label at {far}")
    if ks.symbol_by_ref(root, "R_TRIM") is None:               # R_TRIM: RFB2.2 (/FB_TRIM) -> R_TRIM -> GND wire
        p2 = ks.pin_points(sch, root, "RFB2")["2"]
        clone_resistor(root, sch, "RFB2", "R_TRIM", (p2[0], p2[1] + 3.81), 0)
        rp = ks.pin_points(sch, root, "R_TRIM")
        low = max(rp.values(), key=lambda p: p[1])
        for kind, pts, node in ks.items_at(sch, p2):
            if kind == "wire":                                 # shorten the old RFB2->GND wire to start at R_TRIM pin 2
                xy = list(next(node.children("pts")).children("xy"))
                for e in xy:
                    if abs(float(e.atoms()[1].value) - p2[0]) < 0.01 and abs(float(e.atoms()[2].value) - p2[1]) < 0.01:
                        idx = e.index(e.atoms()[2])
                        e[idx] = ks.Atom(f"{low[1]:g}")
        ks.insert_after(sch, next(sch.children("label")), label_text("FB_TRIM", p2, "FB_TRIM"))
        log.append(f"R_TRIM placed, pins {rp}; GND wire shortened to {low}; label FB_TRIM at {p2}")
    for ref in B2_REFS:
        s = spec[ref]
        sym = ks.symbol_by_ref(root, ref)
        old = {p.atoms()[1].value: p.atoms()[2].value for p in sym.children("property")} if sym is not None else {}
        if old.get("MPN") and old["MPN"] != s["mpn"]:
            # R-006: part changed -> drop the previous part's metadata (manufacturer, spec text, tolerance, datasheet URL)
            for extra in ("Specification", "TCR", "Tolerance", "Manufacturer"):
                ks.remove_property(root, ref, extra)
            ks.set_property(root, ref, "Datasheet", "")
            log.append(f"{ref}: stale metadata of {old['MPN']} removed")
        if NUMERIC.match(s["value"]):
            ks.set_property(root, ref, "Value", s["value"])
        ks.set_property(root, ref, "Footprint", s["footprint"])
        ks.set_or_add_property(root, ref, "MPN", s["mpn"])
    log.append(f"Value/Footprint/MPN set for {len(B2_REFS)} refs")
    return ks.dumps(root), log


def main() -> int:
    sys.path.insert(0, str(ROOT))
    from analysis.check_consistency import parse_spec
    spec, _ = parse_spec(ROOT / "design" / "pdu_v2_spec.yaml")
    new, log = apply(SCH.read_bytes().decode("utf-8"), spec)
    SCH.write_bytes(new.encode("utf-8"))
    print("\n".join(log))
    return 0


if __name__ == "__main__":
    sys.exit(main())
