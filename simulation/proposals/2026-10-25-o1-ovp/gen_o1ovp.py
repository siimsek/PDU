def main():
    inc, changes = circuit_split()
    (HERE/'pdu-circuit-o1ovp.inc').write_text(inc, newline='\n')
    (HERE/'pdu-efuse-block-o1ovp.inc').write_text(efuse_block(), newline='\n')
    (HERE/'pdu-o1ovp-block.inc').write_text(OVP_BLOCK, newline='\n')
    C = cases(); table = {}
    D = HERE/'decks'; D.mkdir(exist_ok=True)
    for old in D.glob('o1ovp-*.cir'): old.unlink()
    for name, c in C.items():
        (D/c['file']).write_text(c['_fn']('lt'), newline='\n')
        (D/c['ng_file']).write_text(c['_fn']('ng'), newline='\n')
