              ('176u', '1m', 'c176', True, '16 x 22 uF x CBIAS 0.5 (board-deck value)', None),
              ('176u', '12.5m', 'c176-esr12m5', True, '16 x 22 uF x CBIAS 0.5, 12.5 mOhm', None),
