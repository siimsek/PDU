def mc_sample(rng, overdrive):
    """One Monte-Carlo sample, uniform inside the guaranteed (G) + assumption (A1) limits used by the
    worst-case corners; uniform is a modelling choice (no distribution is given in any datasheet)."""
    u = lambda lo, hi: rng.uniform(lo, hi)
    dref = 4.105424/4.096 - 1           # same total as wchi/wclo (initial + 12 ppm/K + line + load)
    dr = 2054.1/2050 - 1                # 0.1 % + 10 ppm/K x 100 K
    vio = u(-5e-3, 5e-3) + u(-4.1e-3, 4.1e-3)
    hy = u(1.5e-3, 5e-3)
    return dict(VREF_P=f'{4.096*(1+u(-dref, dref)):.7g}', RT_P=f'{2050*(1+u(-dr, dr)):.6g}',
                RB_P=f'{1150*(1+u(-dr, dr)):.6g}', CMP_VTRIP=f'{vio + hy/2 + overdrive:.6g}',
                CMP_VREL=f'{vio - hy/2:.6g}', CMP_IB=f'{u(-5e-6, 5e-6):.4g}', TDOFF=f'{u(0.3625e-6, 1.0545e-6):.5g}')

def cases():
    C = {}
    def add(name, kind, fn, checks, note='', acceptance=True, params=None):
        C[name] = dict(kind=kind, file=f'o1ovp-{name}.cir', ng_file=f'o1ovp-{name}.ng.cir', checks=checks, note=note,
                       acceptance=acceptance, params=params or {}, _fn=fn)
    # F1 ramp/step overshoot at the three requirement slopes
    for s in ('s007', 's017', 's023'):
        for c in ('wchi', 'typ'):
            add(f'efuse-ovp-{s}-{c}', 'ramp', lambda e, s=s, c=c: deck_ramp(e, c, s), 'ramp')
    # F2 threshold / delay sweep (wchi). In-spec points are acceptance; beyond-spec points are information.
    for td in ('0.3625u', '0.7u', '1.0545u', '1.5u', '2.0u'):
        insp = td in ('0.3625u', '0.7u', '1.0545u')
        add(f'sweep-tdoff{td[:-1].replace(".", "p")}u-s023-wchi', 'sweep', lambda e, td=td: deck_ramp(e, 'wchi', 's023', f'sweep TDOFF={td}', TDOFF=td),
            'ramp', '' if insp else 'BEYOND datasheet max tPD(INP_L)=1.05 us: delay-margin sensitivity only', insp, dict(TDOFF=td))
