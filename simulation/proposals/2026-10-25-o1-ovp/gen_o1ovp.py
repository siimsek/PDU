    return (HDR + f'* full board {title}; RAW split circuit + OVP block. Corner {corner} {over}.\n'
            + libs(engine) + '.include ../pdu-circuit-o1ovp.inc\n.include ../pdu-o1ovp-block.inc\n'
            + params(corner, **over) + f'Vbattery VBAT 0 {vin}\n' + loads +
            'Rbleed VOUT 0 100k\n' + tran + OPT +
            'Bmeasure1 M_ISNS1 0 V=V(ISNS1,RAW)/0.0075\nBmeasure2 M_ISNS2 0 V=V(ISNS2,RAW)/0.0075\n'
            + meas + '.options plotwinsize=0\n.save V(VOUT) V(RAW) V(O1_11V) V(S2E_11V) V(PG_O1) V(PG_S2E) V(IMON_O1) V(IMON_S2E) V(M_ISNS1) V(M_ISNS2)' + SAVE_OVP + '\n.end\n')

